def cm_to_m(value):

    if value is None:
        return None

    return value / 100


def mm_to_m(value):

    if value is None:
        return None

    return value / 1000


def ft_to_m(value):

    if value is None:
        return None

    return value * 0.3048


def inches_to_m(value):

    if value is None:
        return None

    return value * 0.0254


def grams_to_kg(value):

    if value is None:
        return None

    return value / 1000


def pounds_to_kg(value):

    if value is None:
        return None

    return value * 0.45359237